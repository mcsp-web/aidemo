"""Smoke test the pipeline without the heavy model or a real API key.

We inject fake `sentence_transformers` and `anthropic` modules so we can verify
all the plumbing (PDF -> chunks -> retrieval -> prompt assembly) end to end.
The real deploy uses the genuine libraries; the logic exercised here is identical.
"""
import sys, types, io
import numpy as np

# ---- 1. Build a real test PDF ----
from reportlab.pdfgen import canvas
buf = io.BytesIO()
c = canvas.Canvas(buf)
lines_p1 = [
    "Northwind Traders Annual Report 2025",
    "Total revenue for the year was 4.2 million dollars.",
    "The company opened three new regional offices.",
    "Net profit margin improved to 18 percent.",
]
lines_p2 = [
    "The board approved a dividend of 0.75 dollars per share.",
    "Headcount grew from 60 to 95 employees during the year.",
    "The 2026 outlook projects revenue of 5.5 million dollars.",
]
y = 780
for ln in lines_p1:
    c.drawString(72, y, ln); y -= 20
c.showPage()
y = 780
for ln in lines_p2:
    c.drawString(72, y, ln); y -= 20
c.showPage()
c.save()
pdf_bytes = buf.getvalue()
print(f"[ok] built test PDF, {len(pdf_bytes)} bytes")

# ---- 2. Stub sentence_transformers with a deterministic fake embedder ----
# A trivial bag-of-words hashing embedder: good enough to prove retrieval ranks
# the right chunk to the top. The real model is far better; the code path is the same.
class FakeModel:
    def __init__(self, *a, **k): pass
    def encode(self, texts, normalize_embeddings=False, show_progress_bar=False):
        vecs = []
        for t in texts:
            v = np.zeros(256, dtype=np.float32)
            for w in t.lower().split():
                v[hash(w) % 256] += 1.0
            n = np.linalg.norm(v)
            if normalize_embeddings and n > 0:
                v = v / n
            vecs.append(v)
        return np.array(vecs, dtype=np.float32)

fake_st = types.ModuleType("sentence_transformers")
fake_st.SentenceTransformer = FakeModel
sys.modules["sentence_transformers"] = fake_st

# ---- 3. Stub anthropic so we can see the assembled prompt ----
captured = {}
class FakeBlock:
    type = "text"
    text = "Revenue was 4.2 million dollars. (answer generated by stub)"
class FakeResp:
    content = [FakeBlock()]
class FakeMessages:
    def create(self, **kwargs):
        captured.update(kwargs)
        return FakeResp()
class FakeAnthropic:
    def __init__(self, *a, **k): self.messages = FakeMessages()
fake_anth = types.ModuleType("anthropic")
fake_anth.Anthropic = FakeAnthropic
sys.modules["anthropic"] = fake_anth

# ---- 4. Now exercise the real code ----
from app.rag import DocumentIndex
from app.llm import answer

idx = DocumentIndex()
n = idx.build(pdf_bytes, "northwind.pdf")
print(f"[ok] extracted + chunked into {n} chunks across pages")

q = "What was total revenue?"
results = idx.search(q, top_k=3)
print(f"[ok] retrieval returned {len(results)} chunks; top match (page {results[0][0].page}):")
print("      " + results[0][0].text[:70] + "...")
assert "4.2 million" in results[0][0].text, "top chunk should contain the revenue figure"

reply = answer(q, [c.text for c, _ in results])
print(f"[ok] answer() returned: {reply[:60]}...")
assert "system" in captured and "messages" in captured, "prompt should be assembled"
assert "4.2 million" in captured["messages"][0]["content"], "passages should be in the prompt"
print(f"[ok] prompt correctly included the source passages; model={captured['model']}")

print("\nALL CHECKS PASSED ✅  — pipeline plumbing is sound.")
